"""Analyst in the loop (challenge C8): one feedback round, before and after.

Round 0 runs the decision core over the first half of the October holdout.
An analyst reviews every harmful action: on a case the bank later cleared, the
analyst *rejects* the findings in the proof's minimal set; on confirmed fraud,
*accepts* them. Those decisions go through the same feedback ledger the console
uses (governance/feedback.py), and the resulting adjustments are applied — no
retraining — to the second half. Reported: legitimate customers acted against
and frauds missed on the second half, with and without the feedback, and the
feedback ids behind every adjustment.

    python eval/feedback_round.py   -> eval/reports/feedback_round.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # pragma: no cover
    pass

from fraudagent.config import PATHS  # noqa: E402
from fraudagent.core import proof  # noqa: E402
from fraudagent.core.evidence_ledger import trigger_prior  # noqa: E402
from fraudagent.core.signals import SIGNAL_NAMES  # noqa: E402
from fraudagent.governance import feedback as fb  # noqa: E402

MID = pd.Timestamp("2016-10-16")


def decide(r, prior, factors=None):
    fired = [s for s in SIGNAL_NAMES if bool(getattr(r, s)) and s != "customer_disputed"]
    fc = proof.FactContext(trigger_type="risk_score", signal_order=list(SIGNAL_NAMES),
                           exposure_usd=float(r.amount), prior=prior, feedback=factors or {})
    proof.with_fired(fc, set(fired))
    out = proof.decide(set(fired), fc)
    harmful = any(a in proof.HARMFUL for a in out.action_class)
    minimal = proof.minimal_sufficient(fired, fc, out.action_class, fired)[0] if harmful else []
    return harmful, minimal


def main() -> int:
    df = pd.read_parquet(PATHS.staged / "closed_case_facts.parquet")
    tx = pd.read_parquet(PATHS.tx_parquet, columns=["txn_id", "amount"])
    df["amount"] = df["flagged_txn_id"].astype(str).map(
        dict(zip(tx["txn_id"].astype(str), tx["amount"]))).fillna(0.0)
    oct_ = df[df["opened_at"] >= pd.Timestamp("2016-10-01")].sort_values("opened_at")
    first, second = oct_[oct_["opened_at"] < MID], oct_[oct_["opened_at"] >= MID]
    prior = trigger_prior("risk_score")
    records = []
    for r in first.itertuples():
        harmful, minimal = decide(r, prior)
        if not harmful:
            continue
        for f in minimal:
            if f in SIGNAL_NAMES:
                records.append({"id": f"FBR-{len(records) + 1:05d}", "case_id": r.case_id,
                                "target": f, "card_id": r.card_id, "accepted": bool(r.is_fraud)})
    adj = fb.adjustments(records)
    factors = {s: v["factor"] for s, v in adj["signal"].items()}

    def tally(sub, f):
        legit = fraud_hit = 0
        for r in sub.itertuples():
            h, _ = decide(r, prior, f)
            legit += int(h and not r.is_fraud)
            fraud_hit += int(h and r.is_fraud)
        n_f = int(sub["is_fraud"].sum())
        return {"legit_acted_against": legit, "frauds_acted_on": fraud_hit,
                "frauds_missed": n_f - fraud_hit}

    before, after = tally(second, None), tally(second, factors)
    out = {"feedback_records": len(records), "adjustments": adj["signal"],
           "second_half": {"before": before, "after": after}, "n_second_half": len(second)}
    (PATHS.eval_out / "feedback_round.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    md = ["# Analyst in the loop — one feedback round", "",
          f"Generated by `eval/feedback_round.py`. {len(records)} analyst decisions on the "
          f"harmful actions of 1–15 October; behaviour measured on 16–31 October "
          f"({len(second)} replays). No model is retrained: the decisions shrink the reliability "
          f"of signals analysts repeatedly rejected.", "",
          "| 16–31 Oct | legit customers acted against | frauds acted on | frauds missed |",
          "|---|--:|--:|--:|",
          f"| before feedback | {before['legit_acted_against']} | {before['frauds_acted_on']} | "
          f"{before['frauds_missed']} |",
          f"| after one round | {after['legit_acted_against']} | {after['frauds_acted_on']} | "
          f"{after['frauds_missed']} |", "", "## What changed, and which decisions caused it", ""]
    for s, v in adj["signal"].items():
        md.append(f"- `{s}` reliability × {v['factor']:.2f}, caused by {len(v['caused_by'])} "
                  f"rejections ({', '.join(v['caused_by'][:6])}{'…' if len(v['caused_by']) > 6 else ''})")
    if not adj["signal"]:
        md.append("- no signal was rejected often enough (2+ net rejections) to change behaviour")
    md += ["", "Entity-scoped rejections (a finding rejected on one card) suppress that finding "
           "on later cases of the same card; they are exercised live through "
           "`POST /api/feedback/{case}` and listed in each answer's `feedback_applied`.", ""]
    (PATHS.eval_out / "feedback_round.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
